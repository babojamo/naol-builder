create or replace function public.reserve_ai_build_usage(p_user_id uuid,p_image_count integer,p_model text)
returns table(import_id uuid,usage_used integer,usage_limit integer)
language plpgsql security definer set search_path='' as $$
declare q public.ai_user_quotas; result_id uuid;
begin
 if p_image_count<1 or p_image_count>8 then raise exception 'Upload between 1 and 8 screenshots' using errcode='22023'; end if;
 insert into public.ai_user_quotas(user_id) values(p_user_id) on conflict(user_id) do nothing;
 select * into q from public.ai_user_quotas where user_id=p_user_id for update;
 if not q.ai_enabled then raise exception 'AI character import is disabled for this account' using errcode='PT403'; end if;
 if q.usage_used>=q.usage_limit then raise exception 'No AI imports remain' using errcode='PT429'; end if;
 update public.ai_user_quotas set usage_used=usage_used+1 where user_id=p_user_id returning * into q;
 insert into public.ai_build_imports(user_id,status,image_count,model_used) values(p_user_id,'reserved',p_image_count,p_model) returning id into result_id;
 return query select result_id,q.usage_used,q.usage_limit;
end $$;

create or replace function public.complete_ai_build_import(p_import_id uuid,p_result jsonb,p_normalized jsonb default null)
returns void language plpgsql security definer set search_path='' as $$
begin
 update public.ai_build_imports set status='completed',result_json=p_result,normalized_json=p_normalized,completed_at=now(),error_code=null,error_message=null
 where id=p_import_id and status in ('reserved','processing');
 if not found then raise exception 'AI import reservation is no longer active' using errcode='PT409'; end if;
end $$;

create or replace function public.refund_ai_build_import(p_import_id uuid,p_error_code text,p_error_message text)
returns void language plpgsql security definer set search_path='' as $$
declare uid uuid;
begin
 select user_id into uid from public.ai_build_imports where id=p_import_id and status in ('reserved','processing') for update;
 if not found then return; end if;
 update public.ai_build_imports set status='failed',error_code=left(p_error_code,80),error_message=left(p_error_message,300),completed_at=now() where id=p_import_id;
 update public.ai_user_quotas set usage_used=greatest(0,usage_used-1) where user_id=uid;
end $$;

create or replace function public.admin_apply_ai_quota(p_admin uuid,p_target uuid,p_action text,p_value integer default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare q public.ai_user_quotas; before_data jsonb; after_data jsonb;
begin
 if not exists(select 1 from public.app_admins where user_id=p_admin) then raise exception 'Administrator access required' using errcode='42501'; end if;
 insert into public.ai_user_quotas(user_id) values(p_target) on conflict(user_id) do nothing;
 select * into q from public.ai_user_quotas where user_id=p_target for update;
 before_data:=jsonb_build_object('usage_used',q.usage_used,'usage_limit',q.usage_limit,'ai_enabled',q.ai_enabled);
 if p_action='ai_reset' then update public.ai_user_quotas set usage_used=0 where user_id=p_target;
 elsif p_action='ai_limit_change' then if p_value is null or p_value<0 or p_value>10000 then raise exception 'Invalid AI usage limit'; end if; update public.ai_user_quotas set usage_limit=greatest(p_value,usage_used) where user_id=p_target;
 elsif p_action='ai_enabled_change' then update public.ai_user_quotas set ai_enabled=(p_value=1) where user_id=p_target;
 elsif p_action='ai_uses_granted' then if p_value is null or p_value<1 or p_value>10000 then raise exception 'Invalid AI use grant'; end if; update public.ai_user_quotas set usage_limit=least(10000,usage_limit+p_value) where user_id=p_target;
 else raise exception 'Unsupported administration action'; end if;
 select * into q from public.ai_user_quotas where user_id=p_target;
 after_data:=jsonb_build_object('usage_used',q.usage_used,'usage_limit',q.usage_limit,'ai_enabled',q.ai_enabled);
 insert into public.admin_audit_log(admin_user_id,target_user_id,action,before_data,after_data) values(p_admin,p_target,p_action,before_data,after_data);
 return after_data;
end $$;

revoke all on function public.reserve_ai_build_usage(uuid,integer,text),public.complete_ai_build_import(uuid,jsonb,jsonb),public.refund_ai_build_import(uuid,text,text),public.admin_apply_ai_quota(uuid,uuid,text,integer) from public,anon,authenticated;
grant execute on function public.reserve_ai_build_usage(uuid,integer,text),public.complete_ai_build_import(uuid,jsonb,jsonb),public.refund_ai_build_import(uuid,text,text),public.admin_apply_ai_quota(uuid,uuid,text,integer) to service_role;

commit;
